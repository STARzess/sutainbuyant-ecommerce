import { spawn } from "node:child_process";
import { once } from "node:events";
import path from "node:path";
import fs from "node:fs";
import { startMockApi } from "./mock-api.mjs";
const apiPort = Number(process.env.QA_API_PORT || 4325);
const appPort = Number(process.env.QA_APP_PORT || 3105);
const mock = startMockApi(apiPort); await once(mock, "listening");
const project = process.cwd();
const directory = process.env.QA_EMPTY_CATALOG === "1" ? ".next-e2e-empty-workspace" : ".next-e2e-workspace";
const copy = path.resolve(project, directory);
if (!copy.startsWith(path.resolve(project) + path.sep) || path.basename(copy) !== directory) throw new Error("Invalid test checkout");
if (fs.existsSync(copy)) {
  if (!fs.existsSync(path.join(copy, ".generated-test-checkout"))) throw new Error("Test directory contains unrecognized files");
  for (const directory of ["src", "public"]) {
    const target = path.resolve(copy, directory);
    if (!target.startsWith(copy + path.sep)) throw new Error("Invalid generated source target");
    fs.rmSync(target, { recursive: true, force: true });
  }
}
fs.mkdirSync(copy, { recursive: true }); fs.writeFileSync(path.join(copy, ".generated-test-checkout"), "Generated by tests/e2e/server.mjs");
for (const file of ["src", "public", "package.json", "package-lock.json", "next.config.ts", "tsconfig.json"]) fs.cpSync(path.join(project, file), path.join(copy, file), { recursive: true });
if (!fs.existsSync(path.join(copy, "node_modules"))) fs.symlinkSync(path.join(project, "node_modules"), path.join(copy, "node_modules"), process.platform === "win32" ? "junction" : "dir");
const env = { ...process.env, NEXT_PUBLIC_API_URL: `http://127.0.0.1:${apiPort}/api/v1`, NEXT_PUBLIC_SITE_URL: `http://127.0.0.1:${appPort}`, NEXT_DIST_DIR: ".next", NEXT_TEST_WORKSPACE_ROOT: project, NEXT_TELEMETRY_DISABLED: "1" };
delete env.NO_COLOR;
const next = path.join(project, "node_modules/next/dist/bin/next");
let child = spawn(process.execPath, [next, "build"], { cwd: copy, env, stdio: "inherit", windowsHide: true });
const [code] = await once(child, "exit");
if (code !== 0) { mock.close(); process.exit(code || 1); }
child = spawn(process.execPath, [next, "start", "--hostname", "127.0.0.1", "--port", String(appPort)], { cwd: copy, env, stdio: "inherit", windowsHide: true });
function stop() { child.kill(); mock.close(); }
process.on("SIGINT", stop); process.on("SIGTERM", stop);
child.on("exit", code => { mock.close(); process.exit(code || 0); });
